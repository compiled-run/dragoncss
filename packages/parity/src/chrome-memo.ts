// Chrome's output for one capture, remembered by everything that decides it: the page sent to Chrome, the code that drives the
// page, the pinned Chrome and the machine. A regen step re-run for a compiler change its pages do not show reuses the bytes
// instead of rendering again. The memo lives beside regen's cache (.git/dragon-regen/v2), which CI carries between rounds and
// prunes after 30 days unused. It is on only with DRAGON_CHROME_MEMO=1, which pnpm regen sets for its steps (DRAGON_CHROME_MEMO=0
// before pnpm regen renders everything afresh); tests and direct runs always render.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, renameSync, statSync, utimesSync, writeFileSync } from 'node:fs';
import { release } from 'node:os';
import { join, resolve } from 'node:path';
import { CHROME_VERSION, PLAYWRIGHT_VERSION } from './chrome.ts';
import { repoPath } from './paths.ts';
import { hostPlatform } from './platform.ts';

let dir: string | null = null;

/** The git common directory of a checkout: .git itself, or for a worktree the commondir its .git file leads to. */
export function gitCommonDir(root: string): string {
  const dotGit = join(root, '.git');
  if (statSync(dotGit).isDirectory()) return dotGit;
  const m = /^gitdir: (.+)$/m.exec(readFileSync(dotGit, 'utf8'));
  if (m === null) throw new Error(`${dotGit} names no gitdir`);
  const gitDir = resolve(root, m[1]!.trim());
  const common = join(gitDir, 'commondir');
  return existsSync(common) ? resolve(gitDir, readFileSync(common, 'utf8').trim()) : gitDir;
}

/** The memo directory of a capture kind, beside regen's cache in the git common directory (shared by every worktree). */
export function memoDir(kind: string): string {
  dir ??= gitCommonDir(repoPath('.'));
  return join(dir, 'dragon-regen', 'v2', `chrome-memo-${kind}`);
}

/**
 * The banner comment of Dragon's web CSS (emit/web-css.ts). Its compilation digest covers the committed web profile, the
 * compiler and the whole input, so every profile-rows rewrite changed it on every compiled page and no compiled page was ever
 * remembered. A comment changes nothing Chrome renders or computes, so the key reads it without the digest.
 */
const DRAGON_BANNER = /\/\* Generated by Dragon from compilation [0-9a-f]{64}\. Do not edit\. \*\//g;

/**
 * The memo key: kind, the JSON of parts (everything sent to Chrome, Dragon's banner digest aside), the content of code (repo
 * paths of the modules that drive the page, which must be in the capture's own import closure so regen keys them), the pinned
 * Chrome and this machine.
 */
export function memoKey(kind: string, parts: unknown, code: readonly string[]): string {
  const h = createHash('sha256');
  const page = JSON.stringify({ kind, chrome: CHROME_VERSION, playwright: PLAYWRIGHT_VERSION, platform: hostPlatform(), os: release(), parts });
  h.update(page.replace(DRAGON_BANNER, '/* Generated by Dragon. Do not edit. */'));
  for (const p of [...code].sort()) h.update('\0').update(p).update('\0').update(readFileSync(repoPath(p)));
  return h.digest('hex');
}

export type MemoStats = { hits: number; misses: number };

/** Which produced bytes to remember: keep returns false for a result that a later run could change (a timeout, say). */
export type Keep = (bytes: Buffer) => boolean;

/** produce()'s bytes for this key: the remembered ones when present, else produced now and remembered when keep allows. */
export function memoized(kind: string, parts: unknown, code: readonly string[], stats: MemoStats, produce: () => Promise<Buffer>, keep?: Keep): Promise<Buffer> {
  return memoizedIn(memoDir(kind), kind, parts, code, stats, produce, keep);
}

/** memoized with the memo in directory d. */
export async function memoizedIn(d: string, kind: string, parts: unknown, code: readonly string[], stats: MemoStats, produce: () => Promise<Buffer>, keep: Keep = () => true): Promise<Buffer> {
  if (process.env['DRAGON_CHROME_MEMO'] !== '1') return produce();
  const file = join(d, memoKey(kind, parts, code));
  if (existsSync(file)) {
    stats.hits++;
    const now = new Date();
    utimesSync(file, now, now);
    return readFileSync(file);
  }
  stats.misses++;
  const bytes = await produce();
  if (!keep(bytes)) return bytes;
  mkdirSync(d, { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  writeFileSync(tmp, bytes);
  renameSync(tmp, file);
  return bytes;
}

/** memoized for a JSON-able value: remembered as its JSON text when keep allows. */
export async function memoizedJson<T>(kind: string, parts: unknown, code: readonly string[], stats: MemoStats, produce: () => Promise<T>, keep: (value: T) => boolean = () => true): Promise<T> {
  const bytes = await memoized(kind, parts, code, stats, async () => Buffer.from(JSON.stringify(await produce())), (b) => keep(JSON.parse(b.toString('utf8')) as T));
  return JSON.parse(bytes.toString('utf8')) as T;
}

/** LB1: AI, SG, XX and SA without Mn/Mc resolve to AL, SA with Mn/Mc to CM, CJ to NS (strict) or ID (normal). */
function resolveClass(c: number, cjIsIdeographic: boolean): number {
  if (c === LB_AI || c === LB_SG || c === LB_XX || c === LB_SA) return LB_AL;
  if (c === LB_SA_M) return LB_CM;
  if (c === LB_CJ) return cjIsIdeographic ? LB_ID : LB_NS;
  return c;
}

function isQu(c: number): boolean {
  return c === LB_QU || c === LB_QU_PI || c === LB_QU_PF;
}

/** The text after LB9 and LB10: one unit per combining sequence, carrying its base code point's class and properties. */
type Units = {
  readonly cls: readonly number[];
  readonly cp: readonly number[];
  readonly wide: readonly boolean[];
  readonly start: readonly number[];
};

function unitsOf(text: readonly number[], cjIsIdeographic: boolean): Units {
  const cls: number[] = [];
  const cp: number[] = [];
  const wide: boolean[] = [];
  const start: number[] = [];
  for (let i = 0; i < text.length; i++) {
    const ch = text[i] as number;
    const c = resolveClass(lineBreakClass(ch), cjIsIdeographic);
    if (c === LB_CM || c === LB_ZWJ) {
      const n = cls.length;
      const base = n > 0 ? (cls[n - 1] as number) : LB_SP;
      // LB9: X (CM | ZWJ)* is X, for X not BK, CR, LF, NL, SP or ZW.
      if (n > 0 && base !== LB_BK && base !== LB_CR && base !== LB_LF && base !== LB_NL && base !== LB_SP && base !== LB_ZW) continue;
      // LB10: any remaining CM or ZWJ is AL.
      cls.push(LB_AL);
    } else {
      cls.push(c);
    }
    cp.push(ch);
    wide.push(isEastAsian(ch));
    start.push(i);
  }
  return { cls, cp, wide, start };
}

function clsAt(u: Units, k: number): number {
  return k >= 0 && k < u.cls.length ? (u.cls[k] as number) : -1;
}

/** Index of the first unit before k that is not SP (-1 when there is none). */
function skipSpacesBack(u: Units, k: number): number {
  let j = k;
  while (j >= 0 && (u.cls[j] as number) === LB_SP) j--;
  return j;
}

function isAkDottedAs(u: Units, k: number): boolean {
  const c = clsAt(u, k);
  return c === LB_AK || c === LB_AS || (k >= 0 && k < u.cp.length && (u.cp[k] as number) === DOTTED_CIRCLE);
}

/** Whether UAX #14 allows a break before unit k (k >= 1), given the raw text for LB8a. */
function unitBreak(u: Units, k: number, text: readonly number[]): boolean {
  const p = clsAt(u, k - 1);
  const c = clsAt(u, k);
  const n = clsAt(u, k + 1);
  // LB4, LB5
  if (p === LB_BK) return true;
  if (p === LB_CR && c === LB_LF) return false;
  if (p === LB_CR || p === LB_LF || p === LB_NL) return true;
  // LB6, LB7
  if (c === LB_BK || c === LB_CR || c === LB_LF || c === LB_NL) return false;
  if (c === LB_SP || c === LB_ZW) return false;
  // LB8: ZW SP* ÷
  const beforeSpaces = skipSpacesBack(u, k - 1);
  if (clsAt(u, beforeSpaces) === LB_ZW) return true;
  // LB8a: ZWJ ×
  if ((text[(u.start[k] as number) - 1] as number) === ZWJ) return false;
  // LB11
  if (c === LB_WJ || p === LB_WJ) return false;
  // LB12, LB12a
  if (p === LB_GL) return false;
  if (c === LB_GL && p !== LB_SP && p !== LB_BA && p !== LB_HY) return false;
  // LB13
  if (c === LB_CL || c === LB_CP || c === LB_EX || c === LB_SY) return false;
  // LB14: OP SP* ×
  if (clsAt(u, beforeSpaces) === LB_OP) return false;
  // LB15a: (sot | BK | CR | LF | NL | OP | QU | GL | SP | ZW) [\p{Pi}&QU] SP* ×
  if (clsAt(u, beforeSpaces) === LB_QU_PI) {
    const b = clsAt(u, beforeSpaces - 1);
    if (beforeSpaces === 0 || b === LB_BK || b === LB_CR || b === LB_LF || b === LB_NL || b === LB_OP || isQu(b) || b === LB_GL || b === LB_SP || b === LB_ZW) return false;
  }
  // LB15b: × [\p{Pf}&QU] ( SP | GL | WJ | CL | QU | CP | EX | IS | SY | BK | CR | LF | NL | ZW | eot)
  if (c === LB_QU_PF) {
    if (k + 1 >= u.cls.length) return false;
    if (n === LB_SP || n === LB_GL || n === LB_WJ || n === LB_CL || isQu(n) || n === LB_CP || n === LB_EX || n === LB_IS || n === LB_SY || n === LB_BK || n === LB_CR || n === LB_LF || n === LB_NL || n === LB_ZW) return false;
  }
  // LB15c: SP ÷ IS NU; LB15d: × IS
  if (p === LB_SP && c === LB_IS && n === LB_NU) return true;
  if (c === LB_IS) return false;
  // LB16: (CL | CP) SP* × NS
  if (c === LB_NS && (clsAt(u, beforeSpaces) === LB_CL || clsAt(u, beforeSpaces) === LB_CP)) return false;
  // LB17: B2 SP* × B2
  if (c === LB_B2 && clsAt(u, beforeSpaces) === LB_B2) return false;
  // LB18
  if (p === LB_SP) return true;
  // LB19: × [QU - \p{Pi}]; [QU - \p{Pf}] ×
  if (c === LB_QU || c === LB_QU_PF) return false;
  if (p === LB_QU || p === LB_QU_PI) return false;
  // LB19a: unless surrounded by East Asian characters, do not break either side of any quotation mark.
  if (isQu(c)) {
    if (!(u.wide[k - 1] as boolean)) return false;
    if (k + 1 >= u.cls.length || !(u.wide[k + 1] as boolean)) return false;
  }
  if (isQu(p)) {
    if (!(u.wide[k] as boolean)) return false;
    if (k - 2 < 0 || !(u.wide[k - 2] as boolean)) return false;
  }
  // LB20
  if (c === LB_CB || p === LB_CB) return true;
  // LB20a: (sot | BK | CR | LF | NL | SP | ZW | CB | GL) (HY | U+2010) × AL
  if ((p === LB_HY || (u.cp[k - 1] as number) === HYPHEN) && c === LB_AL) {
    const b = clsAt(u, k - 2);
    if (k - 2 < 0 || b === LB_BK || b === LB_CR || b === LB_LF || b === LB_NL || b === LB_SP || b === LB_ZW || b === LB_CB || b === LB_GL) return false;
  }
  // LB21
  if (c === LB_BA || c === LB_HY || c === LB_NS || p === LB_BB) return false;
  // LB21a: HL (HY | [BA - $EastAsian]) × [^HL]
  if ((p === LB_HY || (p === LB_BA && !(u.wide[k - 1] as boolean))) && clsAt(u, k - 2) === LB_HL && c !== LB_HL) return false;
  // LB21b
  if (p === LB_SY && c === LB_HL) return false;
  // LB22
  if (c === LB_IN) return false;
  // LB23
  if ((p === LB_AL || p === LB_HL) && c === LB_NU) return false;
  if (p === LB_NU && (c === LB_AL || c === LB_HL)) return false;
  // LB23a
  if (p === LB_PR && (c === LB_ID || c === LB_EB || c === LB_EM)) return false;
  if ((p === LB_ID || p === LB_EB || p === LB_EM) && c === LB_PO) return false;
  // LB24
  if ((p === LB_PR || p === LB_PO) && (c === LB_AL || c === LB_HL)) return false;
  if ((p === LB_AL || p === LB_HL) && (c === LB_PR || c === LB_PO)) return false;
  // LB25
  if (c === LB_PO || c === LB_PR) {
    let j = k - 1;
    if (clsAt(u, j) === LB_CL || clsAt(u, j) === LB_CP) j--;
    while (clsAt(u, j) === LB_SY || clsAt(u, j) === LB_IS) j--;
    if (clsAt(u, j) === LB_NU) return false;
  }
  if (p === LB_PO || p === LB_PR) {
    if (c === LB_NU) return false;
    if (c === LB_OP && n === LB_NU) return false;
    if (c === LB_OP && n === LB_IS && clsAt(u, k + 2) === LB_NU) return false;
  }
  if ((p === LB_HY || p === LB_IS) && c === LB_NU) return false;
  if (c === LB_NU) {
    let j = k - 1;
    while (clsAt(u, j) === LB_SY || clsAt(u, j) === LB_IS) j--;
    if (clsAt(u, j) === LB_NU) return false;
  }
  // LB26
  if (p === LB_JL && (c === LB_JL || c === LB_JV || c === LB_H2 || c === LB_H3)) return false;
  if ((p === LB_JV || p === LB_H2) && (c === LB_JV || c === LB_JT)) return false;
  if ((p === LB_JT || p === LB_H3) && c === LB_JT) return false;
  // LB27
  if ((p === LB_JL || p === LB_JV || p === LB_JT || p === LB_H2 || p === LB_H3) && c === LB_PO) return false;
  if (p === LB_PR && (c === LB_JL || c === LB_JV || c === LB_JT || c === LB_H2 || c === LB_H3)) return false;
  // LB28
  if ((p === LB_AL || p === LB_HL) && (c === LB_AL || c === LB_HL)) return false;
  // LB28a
  if (p === LB_AP && isAkDottedAs(u, k)) return false;
  if (isAkDottedAs(u, k - 1) && (c === LB_VF || c === LB_VI)) return false;
  if (p === LB_VI && isAkDottedAs(u, k - 2) && (c === LB_AK || (u.cp[k] as number) === DOTTED_CIRCLE)) return false;
  if (isAkDottedAs(u, k - 1) && isAkDottedAs(u, k) && n === LB_VF) return false;
  // LB29
  if (p === LB_IS && (c === LB_AL || c === LB_HL)) return false;
  // LB30
  if ((p === LB_AL || p === LB_HL || p === LB_NU) && c === LB_OP && !(u.wide[k] as boolean)) return false;
  if (p === LB_CP && !(u.wide[k - 1] as boolean) && (c === LB_AL || c === LB_HL || c === LB_NU)) return false;
  // LB30a: an odd number of RI before
  if (p === LB_RI && c === LB_RI) {
    let odd = false;
    let j = k - 1;
    while (clsAt(u, j) === LB_RI) {
      odd = !odd;
      j--;
    }
    if (odd) return false;
  }
  // LB30b
  if (c === LB_EM && (p === LB_EB || isExtPictUnassigned(u.cp[k - 1] as number))) return false;
  // LB31
  return true;
}

/**
 * UAX #14 break permission at every boundary of text: result[i] is the boundary before text[i], result[0] is start of text
 * (never) and result[text.length] is end of text (always). Mandatory breaks count as allowed. cjIsIdeographic selects LB1's
 * CSS line-break: normal resolution of CJ to ID (Chrome's ICU) instead of the UAX #14 default, NS.
 */
export function uax14BreakAllowed(text: readonly number[], cjIsIdeographic: boolean): readonly boolean[] {
  const u = unitsOf(text, cjIsIdeographic);
  const out: boolean[] = [];
  let k = 0;
  for (let i = 0; i <= text.length; i++) {
    if (i === text.length) {
      out.push(i > 0);
    } else if (k < u.start.length && (u.start[k] as number) === i) {
      // Boundaries inside a unit (before an attached CM or ZWJ) are LB9's ×.
      out.push(k > 0 && unitBreak(u, k, text));
      k++;
    } else {
      out.push(false);
    }
  }
  return out;
}


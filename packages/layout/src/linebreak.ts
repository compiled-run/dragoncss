/** The index of the last start at or before cp (starts[0] is 0), by a power-of-two search, which needs no rounding. */
function rangeIndex(starts: readonly number[], cp: number): number {
  let step = 1;
  while (step * 2 <= starts.length) step = step * 2;
  let pos = 0;
  while (step >= 1) {
    if (pos + step < starts.length && (starts[pos + step] as number) <= cp) pos = pos + step;
    step = step / 2;
  }
  return pos;
}

/** The Line_Break class code of cp (linebreak-data.ts codes, before LB1 resolution). */
export function lineBreakClass(cp: number): number {
  return LB_VALUES[rangeIndex(LB_STARTS, cp)] as number;
}

function inRanges(starts: readonly number[], ends: readonly number[], cp: number): boolean {
  if (starts.length === 0 || cp < (starts[0] as number)) return false;
  return cp <= (ends[rangeIndex(starts, cp)] as number);
}

/** $EastAsian: East_Asian_Width F, W or H. */
export function isEastAsian(cp: number): boolean {
  return inRanges(EAST_ASIAN_STARTS, EAST_ASIAN_ENDS, cp);
}

function isExtPictUnassigned(cp: number): boolean {
  return inRanges(EXT_PICT_UNASSIGNED_STARTS, EXT_PICT_UNASSIGNED_ENDS, cp);
}


/** A reason the text or style is outside what this module decides, or null. */
function refusal(text: readonly number[], style: LineBreakStyle): string | null {
  if (style.whiteSpaceCollapse !== 'collapse') return `white-space-collapse: ${style.whiteSpaceCollapse} is not supported (only collapse)`;
  if (style.wordBreak !== 'normal') return `word-break: ${style.wordBreak} is not supported (only normal)`;
  if (style.overflowWrap !== 'normal') return `overflow-wrap: ${style.overflowWrap} is not supported (only normal)`;
  if (style.lineBreak !== 'auto') return `line-break: ${style.lineBreak} is not supported (only auto)`;
  if (style.hyphens !== 'manual') return `hyphens: ${style.hyphens} is not supported (only manual)`;
  if (style.languageRules !== 'cj-ideographic') return 'Chinese content languages use ICU line_cj rules, which are not supported';
  for (let i = 0; i < text.length; i++) {
    const cp = text[i] as number;
    const at = `U+${cp.toString(16).toUpperCase()} at ${i}`;
    if ((cp < 0x20 || (cp >= 0x7f && cp <= 0x9f))) return `${at} is a control character; collapsed text has none`;
    const c = lineBreakClass(cp);
    if (c === LB_BK || c === LB_CR || c === LB_LF || c === LB_NL) return `${at} is a forced line break, which is not supported`;
    if (c === LB_SA || c === LB_SA_M) return `${at} needs dictionary-based line breaking (UAX #14 class SA), which is not supported`;
    if (c === LB_SG) return `${at} is a lone surrogate`;
    // Space separators other than U+0020, U+3000 and the no-break spaces: whether they hang at a line end is not measured.
    if (cp === 0x1680 || (cp >= 0x2000 && cp <= 0x200a) || cp === 0x205f) return `${at} is a space separator whose line-end behaviour is not measured`;
  }
  return null;
}


// Line break opportunities (docs/decisions.md, "Text strategy"): native text engines give glyph advances only; Dragon decides
// where lines may break. This is Blink's LazyLineBreakIterator (third_party/blink/renderer/platform/text/text_break_iterator.cc
// at Chrome 145.0.7632.6) over a UAX #14 core that matches ICU 77, the ICU in Chrome 145:
// - spaces (U+0020): never break before one; break after a run of them (BreakSpaceType::kAfterSpaceRun);
// - both code points in U+0021..U+00FF: Blink's fast pair table (LineBreakData in character_property_data_generator.cc):
//   ASCII pairs use Blink's own ASCII table (no break after '/', break after '-' and '?', before '(' '<' '[' '{' after some
//   characters), other pairs use the UAX #14 result for the two code points alone;
// - '-' before an ASCII digit breaks only after an ASCII letter or digit ('ABCD-1234', '2024-01-15', but not ' -5');
// - everything else: UAX #14 over the whole run, with CJ resolved to ID as Chrome's ICU data does (languageRules).
// Soft hyphen (U+00AD) is class BA, so a break follows it; that break shows a hyphen (kind 'soft-hyphen'). NBSP is class GL.
// Pinned data: linebreak-data.ts (Unicode 16.0.0, generated by scripts/gen-linebreak-data.ts).
